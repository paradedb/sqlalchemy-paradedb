from __future__ import annotations

import pytest
from alembic import command
from sqlalchemy import Column, Index, Integer, MetaData, Table, Text, func, select, text

from paradedb.sqlalchemy import pdb, search, tokenizer
from paradedb.sqlalchemy.indexing import ParadeDBField, VectorIndexOptions


pytestmark = pytest.mark.integration


@pytest.mark.parametrize("value", ["50%", "100%%", "%s"])
def test_percent_index_and_query(engine, value):
    items = Table("percent_items", MetaData(), Column("id", Integer, primary_key=True), Column("description", Text))
    config = tokenizer.regex_pattern(f"^{value}$")
    index = Index(
        "percent_idx",
        ParadeDBField(items.c.id),
        ParadeDBField(items.c.description, tokenizer=tokenizer.regex_pattern(f"^{value}$", options={"alias": value})),
        postgresql_using="paradedb",
        postgresql_with=dict(VectorIndexOptions(search_tokenizer=config)),
    )
    with engine.begin() as conn:
        items.create(conn)
        conn.execute(items.insert(), [{"id": 1, "description": value}, {"id": 2, "description": value + "%"}])
        stmt = select(items.c.id).where(
            search.match_any(pdb.alias(items.c.description, value), search.tokenize(value, config))
        )
        assert conn.execute(stmt).scalars().all() == [1]
        # Pass an empty parameter collection so psycopg processes percent escapes.
        literal_sql = str(stmt.compile(dialect=conn.dialect, compile_kwargs={"literal_binds": True}))
        assert conn.exec_driver_sql(literal_sql, {}).scalars().all() == [1]
        assert conn.execute(
            text("SELECT reloptions FROM pg_class WHERE relname = :name"), {"name": index.name}
        ).scalar_one() == [f"search_tokenizer={config.render_search()}"]
        items.drop(conn)


@pytest.mark.parametrize("value", ["50%", "100%%", "%s"])
def test_percent_autogenerated_migration(engine, alembic_config_factory, value):
    metadata = MetaData(schema="percent_migration")
    items = Table(
        "items",
        metadata,
        Column("id", Integer, primary_key=True),
        Column("description", Text),
        Column("category", Text),
    )
    config = tokenizer.regex_pattern(f"^{value}$")
    try:
        with engine.begin() as conn:
            conn.execute(text("CREATE SCHEMA percent_migration"))
            items.create(conn)
            conn.execute(
                items.insert(),
                [
                    {"id": 1, "description": value, "category": value},
                    {"id": 2, "description": None, "category": value},
                    {"id": 3, "description": value, "category": value + "%"},
                ],
            )
        expression = func.coalesce(items.c.description, value)
        Index(
            "percent_idx",
            ParadeDBField(items.c.id),
            ParadeDBField(expression, tokenizer=tokenizer.regex_pattern(f"^{value}$", options={"alias": value})),
            postgresql_using="paradedb",
            postgresql_with=dict(VectorIndexOptions(search_tokenizer=config)),
            postgresql_where=items.c.category == value,
        )
        alembic_config = alembic_config_factory(metadata)
        command.revision(alembic_config, message="percent literals", autogenerate=True)
        command.upgrade(alembic_config, "head")
        with engine.connect() as conn:
            predicate, definition, options = conn.execute(
                text(
                    "SELECT pg_get_expr(i.indpred, i.indrelid), pg_get_indexdef(i.indexrelid), c.reloptions "
                    "FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid "
                    "WHERE i.indexrelid = 'percent_migration.percent_idx'::regclass"
                )
            ).one()
            assert predicate == f"(category = '{value}'::text)"
            assert f"COALESCE(description, '{value}'::text)" in definition
            assert options == [f"search_tokenizer={config.render_search()}"]
            stmt = (
                select(items.c.id)
                .where(
                    items.c.category == value,
                    search.match_any(pdb.alias(expression, value), search.tokenize(value, config)),
                )
                .order_by(items.c.id)
            )
            assert conn.execute(stmt).scalars().all() == [1, 2]
        command.downgrade(alembic_config, "base")
        with engine.connect() as conn:
            assert conn.execute(text("SELECT to_regclass('percent_migration.percent_idx')")).scalar_one() is None
    finally:
        with engine.begin() as conn:
            conn.execute(text("DROP SCHEMA IF EXISTS percent_migration CASCADE"))
